def build_analysis_user_prompt(task: str, message_text: str, channel: str, date: str) -> str:
    return (
        f"ЗАДАЧА ПОЛЬЗОВАТЕЛЯ:\n{task}\n\n"
        f"СООБЩЕНИЕ (канал: {channel}, дата: {date}):\n"
        f"---\n{message_text}\n---\n\n"
        f"Проанализируй это сообщение строго по правилам и верни JSON."
    )


def build_query_parse_prompt(user_query: str, today_iso: str) -> str:
    return f"Текущая дата: {today_iso}\n\nЗапрос пользователя:\n{user_query}"
